//! Colour themes: the terminal's sixteen colours, its ground, text,
//! cursor and selection, and jterm's own chrome made from them. The
//! default is VS Code's 2026 Dark, as its terminal shows it.

#[derive(Clone, Copy, Debug)]
pub struct Theme {
    pub name: &'static str,
    pub dark: bool,
    pub bg: u32,
    pub fg: u32,
    pub cursor: u32,
    pub selection: u32,
    /// Black, red, green, yellow, blue, magenta, cyan, white; then the
    /// bright eight.
    pub ansi: [u32; 16],
}

impl Theme {
    pub fn by_name(name: &str) -> &'static Theme {
        THEMES.iter().find(|t| t.name.eq_ignore_ascii_case(name.trim())).unwrap_or(&THEMES[0])
    }

    fn toward(&self, share: u32) -> u32 {
        crate::canvas::mix(self.bg, self.fg, share)
    }

    /// The line between panes.
    pub fn divider(&self) -> u32 {
        self.toward(if self.dark { 40 } else { 50 })
    }

    /// The caption of a pane you are not in, and its words.
    pub fn idle_caption(&self) -> (u32, u32) {
        (self.toward(if self.dark { 18 } else { 22 }), self.toward(150))
    }

}

const fn t(name: &'static str, dark: bool, bg: u32, fg: u32, cursor: u32, selection: u32, ansi: [u32; 16]) -> Theme {
    Theme { name, dark, bg, fg, cursor, selection, ansi }
}

